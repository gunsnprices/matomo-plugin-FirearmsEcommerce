<?php

/**
 * Copies the gunsnprices PHP parser into vendor/prefixed/gunsnprices/gunsnprices/ under a plugin-specific namespace
 * and writes vendor/autoload.php.
 *
 * Usage:
 *   mkdir /tmp/gnp && cd /tmp/gnp && composer require gunsnprices/gunsnprices:0.1.0
 *   php tools/vendor-library.php /tmp/gnp/vendor/gunsnprices/gunsnprices
 *
 * The library (https://github.com/gunsnprices/gunsnprices-php, Composer gunsnprices/gunsnprices) is seven classes in
 * the GunsNPrices and GunsNPrices\Internal namespaces with no dependencies. Every class reference in it is either a
 * `namespace` line, a `use` line or a global class (\RuntimeException, \LogicException), so the prefix is applied by
 * rewriting those lines. The result is checked with the PHP tokenizer: any name that still starts with the original
 * namespace stops the script.
 *
 * The prefix follows the matomo-scoper convention (Matomo\Dependencies\<PluginName>\...), so this copy cannot clash
 * with another plugin, or another PHP application, that loads the same library in a different version.
 *
 * Dev-only file. It is not part of the plugin package (see "archive" in plugin.json).
 */

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$src = isset($argv[1]) ? rtrim($argv[1], '/') : '';
$root = dirname(__DIR__);
$dest = $root . '/vendor/prefixed/gunsnprices/gunsnprices';
$from = 'GunsNPrices';
$prefix = 'Matomo\\Dependencies\\FirearmsEcommerce\\GunsNPrices';

if ($src === '' || !is_file("$src/src/Parser.php")) {
    fwrite(STDERR, "Usage: php tools/vendor-library.php path/to/gunsnprices-php (a checkout or vendor/gunsnprices/gunsnprices)\n");
    exit(1);
}

function rmtree(string $dir): void
{
    if (!is_dir($dir)) {
        return;
    }
    foreach (scandir($dir) as $f) {
        if ($f === '.' || $f === '..') {
            continue;
        }
        $p = "$dir/$f";
        is_dir($p) ? rmtree($p) : unlink($p);
    }
    rmdir($dir);
}

rmtree($dest);
mkdir("$dest/src/Internal", 0755, true);
mkdir("$dest/data", 0755, true);

$phpFiles = ['src/Parser.php'];
foreach (glob("$src/src/Internal/*.php") as $p) {
    $phpFiles[] = 'src/Internal/' . basename($p);
}
sort($phpFiles);

$version = '';
foreach ($phpFiles as $rel) {
    $code = file_get_contents("$src/$rel");
    $out = preg_replace(
        ['/^namespace ' . $from . '(\\\\|;)/m', '/^use ' . $from . '\\\\/m'],
        ['namespace ' . str_replace('\\', '\\\\', $prefix) . '$1', 'use ' . str_replace('\\', '\\\\', $prefix) . '\\\\'],
        $code
    );
    foreach (token_get_all($out) as $t) {
        if (is_array($t) && in_array($t[0], [T_NAME_QUALIFIED, T_NAME_FULLY_QUALIFIED], true)) {
            $name = ltrim($t[1], '\\');
            if (strpos($name, $from . '\\') === 0) {
                fwrite(STDERR, "Unprefixed name $t[1] in $rel line $t[2]\n");
                exit(1);
            }
        }
    }
    if ($rel === 'src/Parser.php' && preg_match("/const VERSION = '([^']+)'/", $out, $m)) {
        $version = $m[1];
    }
    $header = "<?php\n/*\n * Copy of gunsnprices/gunsnprices (MIT License, see ../LICENSE) bundled with the FirearmsEcommerce Matomo plugin.\n"
        . " * Changed by tools/vendor-library.php: the namespace GunsNPrices was renamed to $prefix.\n */\n";
    $out = preg_replace('/^<\?php\s*\n/', $header, $out, 1);
    file_put_contents("$dest/$rel", $out);
}

foreach (['calibers', 'models', 'entities', 'lowercase', 'source'] as $name) {
    $json = file_get_contents("$src/data/$name.json");
    if (!is_array(json_decode($json, true))) {
        fwrite(STDERR, "Bad JSON: data/$name.json\n");
        exit(1);
    }
    file_put_contents("$dest/data/$name.json", $json);
}
foreach (['LICENSE', 'LICENSE-DATA'] as $f) {
    copy("$src/$f", "$dest/$f");
}
file_put_contents(
    "$dest/README.md",
    "# gunsnprices $version\n\n"
    . "PHP title parser for firearms and ammunition.\n"
    . "Source: https://github.com/gunsnprices/gunsnprices-php (Composer: gunsnprices/gunsnprices).\n\n"
    . "Copied by tools/vendor-library.php with one change: the namespace GunsNPrices\\... became\n"
    . "$prefix\\... so this copy cannot clash with other software that loads the same library.\n\n"
    . "Code: MIT License (LICENSE). Data files data/models.json and data/calibers.json: CC BY 4.0,\n"
    . "GunsNPrices (https://gunsnprices.com), unchanged (LICENSE-DATA).\n"
);

$autoload = <<<'PHP'
<?php

/**
 * Autoloader for the libraries bundled in vendor/prefixed/. Generated by tools/vendor-library.php.
 *
 * The plugin bundles one library, gunsnprices/gunsnprices (MIT), under the namespace
 * Matomo\Dependencies\FirearmsEcommerce\GunsNPrices.
 */

if (!defined('MATOMO_FIREARMSECOMMERCE_AUTOLOAD')) {
    define('MATOMO_FIREARMSECOMMERCE_AUTOLOAD', true);

    spl_autoload_register(static function (string $class): void {
        $prefix = 'Matomo\\Dependencies\\FirearmsEcommerce\\GunsNPrices\\';
        if (strncmp($class, $prefix, strlen($prefix)) !== 0) {
            return;
        }
        $relative = substr($class, strlen($prefix));
        if (!preg_match('/^[A-Za-z0-9_\\\\]+$/', $relative)) {
            return;
        }
        $file = __DIR__ . '/prefixed/gunsnprices/gunsnprices/src/' . str_replace('\\', '/', $relative) . '.php';
        if (is_file($file)) {
            require_once $file;
        }
    }, true, true);
}

PHP;
file_put_contents($root . '/vendor/autoload.php', $autoload);

echo 'Bundled gunsnprices ' . $version . ' into vendor/prefixed/gunsnprices/gunsnprices (' . count($phpFiles) . " PHP files)\n";
